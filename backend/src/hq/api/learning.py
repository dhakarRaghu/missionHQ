@router.post("/lessons/{lesson_date}/post", operation_id="draftPost")
async def draft_post(lesson_date: str, section: str = "writing", kind: str = "topic") -> dict:
    """Prepare this lesson as a post for his own site.

    Tutor rewrites it for a reader with none of his context, the checks run,
    and the file lands in his site's content folder. Nothing is committed,
    pushed or published: that stays his.
    """
    from hq import engine
    from hq.learning_pipeline import POST_SECTIONS, post_brief, post_payload

    if section not in POST_SECTIONS:
        raise HTTPException(400, f"section must be one of {', '.join(POST_SECTIONS)}")
    row = await db.fetchone(
        "SELECT to_char(lesson_date, 'YYYY-MM-DD') AS lesson_date, title, md_path"
        " FROM hq.lessons WHERE lesson_date = %s::date AND kind = %s",
        (lesson_date, kind),
    )
    if not row or not row["md_path"]:
        raise HTTPException(404, f"no {kind} lesson on {lesson_date} to post")
    live = await db.fetchone(
        "SELECT id::text FROM hq.tasks WHERE dedup_key = %s"
        " AND status IN ('backlog', 'running')",
        (f"post:{section}:{lesson_date}",),
    )
    if live:
        return {"started": False, "reason": "already preparing this post",
                "task_id": live["id"]}
    payload = post_payload(dict(row), section)
    task_id = await engine.dispatch(
        agent="tutor",
        title=f"Post draft: {str(row['title'])[:56]}",
        brief=post_brief(payload),
        source="web",
        payload=payload,
        dedup_key=f"post:{section}:{lesson_date}",
    )
    return {"started": True, "task_id": task_id, "title": row["title"]}


@router.post("/field-notes/{name}/post", operation_id="draftPostFromFieldNote")
async def draft_post_from_field_note(name: str, section: str = "writing",
                                     shape: str = "lab", lesson_date: str = "") -> dict:
    """Prepare a post for his site from his field note: what he did and the
    number he got, in his words. `lesson_date` adds that day's lesson as
    background. Nothing is committed, pushed or published.

    Start a note with `python -m hq.site_posts field-note <name>`.
    """
    from hq import engine
    from hq.learning_pipeline import POST_SECTIONS, field_note_payload, post_brief
    from hq.site_posts import field_note_path, field_note_problems, read_field_note

    if section not in POST_SECTIONS:
        raise HTTPException(400, f"section must be one of {', '.join(POST_SECTIONS)}")
    try:
        rel = field_note_path(name)
        payload_ = field_note_payload(rel, section, shape)
    except ValueError as exc:
        raise HTTPException(400, str(exc)) from exc
    path = settings().vault_dir / rel
    if not path.is_file():
        raise HTTPException(404, f"no field note at {rel}")
    unfilled = field_note_problems(read_field_note(path.read_text()))
    if unfilled:
        raise HTTPException(400, "; ".join(unfilled))
    if lesson_date:
        row = await db.fetchone(
            "SELECT md_path FROM hq.lessons WHERE lesson_date = %s::date"
            " ORDER BY created_at DESC LIMIT 1", (lesson_date,))
        if not row or not row["md_path"]:
            raise HTTPException(404, f"no lesson on {lesson_date}")
        payload_["md_path"] = str(row["md_path"])
    key = f"post:{section}:{rel}"
    live = await db.fetchone(
        "SELECT id::text FROM hq.tasks WHERE dedup_key = %s"
        " AND status IN ('backlog', 'running')", (key,))
    if live:
        return {"started": False, "reason": "already preparing this post",
                "task_id": live["id"]}
    task_id = await engine.dispatch(
        agent="tutor",
        title=f"Post draft: {payload_['title'][:56]}",
        brief=post_brief(payload_),
        source="web",
        payload=payload_,
        dedup_key=key,
    )
    return {"started": True, "task_id": task_id, "title": payload_["title"]}


@router.post("/courses/{course}/phases/{slug}/teach", operation_id="teachPhase")
async def teach_phase(course: str, slug: str, force: bool = False) -> dict:
    """Study one named phase now, instead of waiting for tonight's run.

    An unread lesson does not hold it (he dropped that rule on 2026-10-06);
    a course lesson he failed in review does, because it needs his decision.

    `force=true` is the rebuild. He has the page already and wants it written
    again, usually because the kit or the standard moved under it, so neither
    the failed-review hold nor "this phase is taught" applies.
    """
    from hq import engine
    from hq.learning_pipeline import course_payload, course_study_brief

    failed = None if force else await db.fetchone(
        "SELECT title FROM hq.lessons WHERE kind = 'course' AND review_status = 'failed'"
        " ORDER BY lesson_date DESC LIMIT 1",
        (),
    )
    if failed:
        return {"started": False,
                "reason": f"{failed['title']} failed review and needs a decision"}

    wanted = ("pending", "taught") if force else ("pending",)
    phase = await db.fetchone(
        "SELECT slug, course, title, summary, url, source FROM hq.course_phases"
        " WHERE slug = %s AND course = %s AND status = ANY(%s)",
        (slug, course, list(wanted)),
    )
    if not phase:
        raise HTTPException(404, f"no {' or '.join(wanted)} phase {slug!r} in {course!r}")
    if phase["source"] == "local":
        return {"started": False, "reason": (
            "this phase is planned, not published. Generate it with Claude"
            f" (/study {course}) and publish it; Mission HQ adds to it after the"
            " next sync.")}

    # Dedup against work that is still alive, never against work that
    # finished. The key used to be the bare slug, so asking to teach a phase
    # again — after resetting it to pending to regenerate the lesson —
    # silently returned yesterday's completed task id and reported
    # {"started": true}. Nothing ran, and the reply said it had.
    live = await db.fetchone(
        "SELECT id::text FROM hq.tasks WHERE dedup_key LIKE %s"
        " AND status IN ('backlog', 'queued', 'running') LIMIT 1",
        (f"course-phase:{slug}%",),
    )
    if live:
        return {"started": False, "reason": "already studying this phase",
                "task_id": live["id"]}
    done = await db.fetchone(
        "SELECT count(*) AS n FROM hq.tasks WHERE dedup_key LIKE %s",
        (f"course-phase:{slug}%",),
    )
    attempt = int((done or {}).get("n") or 0)

    payload = course_payload(dict(phase))
    task_id = await engine.dispatch(
        agent="hunter",
        title=f"Study: {str(phase['title'])[:64]}",
        brief=course_study_brief(payload),
        source="web",
        payload=payload,
        dedup_key=f"course-phase:{slug}" + (f":a{attempt}" if attempt else ""),
    )
    return {"started": True, "task_id": task_id, "title": phase["title"]}


@router.post("/courses/{course}/phases/{slug}/read", operation_id="markPhaseRead")
async def mark_phase_read(course: str, slug: str) -> dict:
    """He finished this phase. Unlocks the next one for the evening run."""
    row = await db.fetchone(
        "UPDATE hq.course_phases SET read_at = coalesce(read_at, now())"
        " WHERE slug = %s AND course = %s RETURNING lesson_id::text, title",
        (slug, course),
    )
    if not row:
        raise HTTPException(404, f"no phase {slug!r} in {course!r}")
    if row["lesson_id"]:
        await mark_read(str(row["lesson_id"]))
    return {"ok": True, "title": row["title"]}


@router.get("/courses/{course}/phases/{slug}/content", operation_id="getPhaseContent")
async def get_phase_content(course: str, slug: str) -> dict[str, Any]:
    """The phase's original text, as he and Claude wrote it.

    What he reads is the enhanced page Mission HQ builds from this. The
    original is shown until that page exists, and stays one click away.
    """
    import httpx

    from hq.tools.learning_tools import fetch_platform_document, read_course_source_text

    phase = await db.fetchone(
        "SELECT slug, source, url FROM hq.course_phases WHERE slug = %s AND course = %s",
        (slug, course),
    )
    if not phase:
        raise HTTPException(404, f"no phase {slug!r} in {course!r}")
    if phase["source"] != "platform":
        return {"slug": slug, "source": phase["source"], "published": False,
                "content": "", "original_url": ""}
    # The repo copy first: it is what he and Claude wrote. The platform is the
    # fallback for a phase generated on another machine.
    content = read_course_source_text(slug)
    doc: dict[str, Any] = {}
    if not content:
        try:
            doc = await fetch_platform_document(slug)
        except (httpx.HTTPError, ValueError) as exc:
            raise HTTPException(502, f"the study platform did not return {slug}: {exc}") from exc
        content = doc["content"]
    return {
        "slug": slug,
        "source": "platform",
        "published": True,
        "title": doc.get("title") or "",
        "summary": doc.get("summary") or "",
        "minutes": doc.get("estimatedMinutes") or 0,
        "tags": doc.get("tags") or [],
        "content": content,
        "original_url": phase["url"],
    }


@router.post("/courses/{course}/activate", operation_id="activateCourse")
async def activate_course(course: str) -> dict:
    """Work this course next, and only this one."""
    row = await db.fetchone(
        "SELECT count(*) AS n FROM hq.course_phases WHERE course = %s", (course,)
    )
    if not row or not row["n"]:
        raise HTTPException(404, f"no course {course!r}")
    await db.execute(
        "INSERT INTO hq.control (key, value) VALUES (%s, to_jsonb(%s::text))"
        " ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value",
        (ACTIVE_COURSE_KEY, course),
    )
    return {"active": course}
