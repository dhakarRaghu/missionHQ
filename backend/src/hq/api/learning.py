"""The learning journey for the console: lessons, the ledger, and the page.

The page endpoint is the interesting one. Tutor writes each lesson twice — a
markdown note and a self-contained HTML page with a diagram — and that HTML
is generated by a model from web-derived study digests. It is not trusted
markup, so it never runs in the console's own origin: the console fetches it
as text and renders it inside a sandboxed frame with no same-origin access,
and this endpoint injects a Content-Security-Policy meta that blocks every
outside load. Two independent walls, because the console holds the session
that can start agents.
"""

from __future__ import annotations

import re
from pathlib import Path, PurePosixPath
from typing import Annotated, Any

from fastapi import APIRouter, Depends, HTTPException, Query
from pydantic import BaseModel, Field

from hq import db
from hq.api.deps import require_auth
from hq.config import settings
from hq.learning_pipeline import LESSON_DIR

router = APIRouter(prefix="/learning", dependencies=[Depends(require_auth)])

PAGE_MAX_CHARS = 2_000_000
# Inline style and script only: the page's diagram needs both, and nothing
# else is allowed to load at all — no CDN, no font, no tracking pixel, no
# fetch back to the API. `data:` images let a lesson embed a small asset.
CSP = (
    "default-src 'none'; style-src 'unsafe-inline'; script-src 'unsafe-inline';"
    " img-src data:; font-src data:; form-action 'none'; base-uri 'none'"
)
_HEAD_RE = re.compile(r"<head[^>]*>", re.IGNORECASE)


_FRONTMATTER_RE = re.compile(r"\A---\n.*?\n---\n", re.DOTALL)


def _with_csp(html: str) -> str:
    """Make one generated page safe to render in the frame.

    Three things, each learned the hard way on 2026-09-12:

    * The content policy, stated inside the document as well as enforced by
      the frame.
    * `<base target="_blank">`, because the lesson links to its sources and
      those links carried no target. Clicking one navigated the FRAME to the
      live site — the owner clicked a source and found himself looking at
      rubyhack.ai inside his own console, reasonably alarmed. Nothing was
      downloaded; the frame had simply been hijacked by an ordinary link.
    * A leading vault frontmatter block, stripped. Tutor stamps one on notes,
      and before `<!DOCTYPE html>` it renders as stray text and drops the page
      into quirks mode.
    """
    html = _FRONTMATTER_RE.sub("", html, count=1)
    head = f'<meta http-equiv="Content-Security-Policy" content="{CSP}">' \
           '<base target="_blank">'
    match = _HEAD_RE.search(html)
    if match:
        return html[: match.end()] + head + html[match.end():]
    return head + html


def _lesson_file(path: str, suffix: str) -> Path:
    """Resolve one lesson file in the repo, or refuse.

    Lessons live in `learning/lessons/`, not the vault. The page endpoint
    returns markup the browser executes in a frame, so the reach here is one
    directory and one suffix, never a path the caller chooses.
    """
    rel = PurePosixPath(path)
    if rel.is_absolute() or ".." in rel.parts:
        raise HTTPException(400, f"invalid lesson path: {path}")
    if not path.startswith(f"{LESSON_DIR}/") or not path.endswith(suffix):
        raise HTTPException(400, f"not a lesson {suffix}: {path}")
    root = settings().learning_dir.resolve()
    full = (root.parent / rel).resolve()
    if not full.is_file() or root not in full.parents:
        raise HTTPException(404, f"no such lesson file: {path}")
    return full


@router.get("/lessons", operation_id="listLessons")
async def list_lessons(limit: int = 30, kind: str = "") -> list[dict[str, Any]]:
    """Lessons, newest first: what he was taught and what it was built from.

    `kind` filters: "topic" for the daily open-web lesson, "course" for a
    phase of his own material. The Learn page asks for topic lessons only —
    course articles belong on the Courses page, beside the phase they teach.
    """
    limit = max(1, min(int(limit), 120))
    if kind.strip():
        return await db.fetch(
            "SELECT id::text, to_char(lesson_date, 'YYYY-MM-DD') AS lesson_date,"
            " title, one_liner, topic, md_path, html_path, score, sources, created_at,"
            " kind, course_slug, read_at"
            " FROM hq.lessons WHERE kind = %s ORDER BY lesson_date DESC, created_at DESC"
            " LIMIT %s",
            (kind.strip(), limit),
        )
    return await db.fetch(
        "SELECT id::text, to_char(lesson_date, 'YYYY-MM-DD') AS lesson_date,"
        " title, one_liner, topic, md_path, html_path, score, sources, created_at,"
        " kind, course_slug, read_at"
        " FROM hq.lessons ORDER BY lesson_date DESC LIMIT %s",
        (limit,),
    )


@router.get("/readings", operation_id="listReadings")
async def list_readings(status: str = "", limit: int = 50) -> list[dict[str, Any]]:
    """The reading ledger: what was found, read, taught or skipped."""
    limit = max(1, min(int(limit), 200))
    where = "WHERE status = %s" if status.strip() else ""
    params: tuple[Any, ...] = (status.strip(), limit) if status.strip() else (limit,)
    return await db.fetch(
        "SELECT url, title, author, source, topic, why, score, status,"
        " digest_path, lesson_id::text, first_seen, last_seen"
        f" FROM hq.readings {where} ORDER BY last_seen DESC LIMIT %s",
        params,
    )


@router.get("/page", operation_id="getLessonPage")
async def get_lesson_page(path: Annotated[str, Query(min_length=1)]) -> dict:
    """One lesson page as text, for the console to render in a sandboxed frame.

    Returned as JSON rather than as an HTML response on purpose: the console
    authenticates with a bearer token, and a frame cannot carry one. Handing
    back a string keeps the fetch authenticated and keeps the markup out of
    any origin until the frame the console controls renders it.
    """
    full = _lesson_file(path, ".html")
    try:
        html = full.read_text()
    except UnicodeDecodeError:
        raise HTTPException(415, "lesson page is not text") from None
    if len(html) > PAGE_MAX_CHARS:
        raise HTTPException(413, "lesson page is too large to render")
    return {"path": path, "html": _with_csp(html)}


@router.get("/note", operation_id="getLessonNote")
async def get_lesson_note(path: Annotated[str, Query(min_length=1)]) -> dict:
    """The markdown of one lesson, for the Learn view's text tab.

    Lessons moved out of the vault, so the console reads them here rather than
    through the vault API: he should never have to open the agents' memory
    layer to read his own lesson.
    """
    full = _lesson_file(path, ".md")
    try:
        text = full.read_text()
    except UnicodeDecodeError:
        raise HTTPException(415, "lesson note is not text") from None
    return {"path": path, "content": _FRONTMATTER_RE.sub("", text, count=1)[:PAGE_MAX_CHARS]}


class RequestBody(BaseModel):
    """One thing he wants to learn about, typed into the Learn page."""

    text: str = Field(min_length=3, max_length=400)


@router.get("/requests", operation_id="listLearningRequests")
async def list_learning_requests(status: str = "open", limit: int = 20) -> list[dict[str, Any]]:
    """What he has asked to learn, newest first."""
    limit = max(1, min(int(limit), 100))
    where = "WHERE status = %s" if status.strip() else ""
    params: tuple[Any, ...] = (status.strip(), limit) if status.strip() else (limit,)
    return await db.fetch(
        "SELECT id::text, text, status, created_at, served_at"
        f" FROM hq.learning_requests {where} ORDER BY created_at DESC LIMIT %s",
        params,
    )


@router.post("/requests", operation_id="addLearningRequest", status_code=201)
async def add_learning_request(body: RequestBody) -> dict:
    """Ask for something specific. The next morning run serves it first."""
    row = await db.fetchone(
        "INSERT INTO hq.learning_requests (text) VALUES (%s) RETURNING id::text",
        (body.text.strip(),),
    )
    return {"id": (row or {}).get("id", "")}


@router.post("/requests/{request_id}/drop", operation_id="dropLearningRequest")
async def drop_learning_request(request_id: str) -> dict:
    """Change his mind. Dropped rather than deleted, so a served request keeps
    its link to the lesson that answered it."""
    await db.execute(
        "UPDATE hq.learning_requests SET status = 'dropped' WHERE id = %s::uuid",
        (request_id,),
    )
    return {"ok": True}


@router.post("/lessons/{lesson_date}/read", operation_id="markLessonRead")
async def mark_lesson_read(lesson_date: str, kind: str = "course") -> dict:
    """Mark a lesson read, which unlocks the next course phase.

    His rule: "if I have read that last article then generate the next,
    otherwise articles will pile up". The evening course run refuses to start
    a new phase while the previous course lesson is unread, so this button is
    the thing that advances the course.
    """
    row = await db.fetchone(
        "UPDATE hq.lessons SET read_at = now()"
        " WHERE lesson_date = %s::date AND kind = %s AND read_at IS NULL"
        " RETURNING title",
        (lesson_date, kind),
    )
    return {"ok": row is not None, "title": (row or {}).get("title", "")}


ACTIVE_COURSE_KEY = "learning:active_course"


async def _active_course() -> str:
    row = await db.fetchone(
        "SELECT value FROM hq.control WHERE key = %s", (ACTIVE_COURSE_KEY,)
    )
    return str((row or {}).get("value") or "").strip('"')


@router.get("/courses", operation_id="listCourses")
async def list_courses() -> list[dict[str, Any]]:
    """His own courses and how far through each one he is.

    One is active at a time. He was explicit: "we will be learning all topic
    one by one, not all in one" — so the evening run works the active course
    and leaves the rest alone.
    """
    active = await _active_course()
    rows = await db.fetch(
        "SELECT course, count(*) AS phases,"
        " count(*) FILTER (WHERE status = 'taught') AS taught,"
        " coalesce(sum(minutes), 0) AS minutes,"
        " min(title) FILTER (WHERE status = 'pending') AS next_title"
        " FROM hq.course_phases GROUP BY course ORDER BY course",
        (),
    )
    return [{**r, "active": r["course"] == active} for r in rows]


@router.get("/courses/{course}", operation_id="getCoursePhases")
async def get_course_phases(course: str) -> list[dict[str, Any]]:
    """Every phase of one course, in order, with the article written for it.

    The row carries the generated lesson's paths, not just a link back to his
    own platform. The whole point of course mode is that he reads the version
    written here — deeper, corrected, with the production failure attached —
    rather than going back to the source module.
    """
    return await db.fetch(
        "SELECT p.slug, p.phase_order, p.title, p.summary, p.difficulty,"
        " p.minutes, p.status, p.url, p.lesson_id::text,"
        " l.html_path AS lesson_html_path, l.md_path AS lesson_md_path,"
        " l.title AS lesson_title, l.one_liner AS lesson_one_liner,"
        " to_char(l.lesson_date, 'YYYY-MM-DD') AS lesson_date,"
        " l.score AS lesson_score, l.read_at AS lesson_read_at"
        " FROM hq.course_phases p"
        " LEFT JOIN hq.lessons l ON l.id = p.lesson_id"
        " WHERE p.course = %s ORDER BY p.phase_order",
        (course,),
    )


@router.post("/courses/{course}/phases/{slug}/teach", operation_id="teachPhase")
async def teach_phase(course: str, slug: str) -> dict:
    """Study one named phase now, instead of waiting for tonight's run.

    Still gated: it will not start while a course lesson sits unread, because
    that is the rule that stops articles piling up.
    """
    from hq import engine
    from hq.learning_pipeline import course_payload, course_study_brief

    unread = await db.fetchone(
        "SELECT title FROM hq.lessons WHERE kind = 'course' AND read_at IS NULL"
        " ORDER BY lesson_date DESC LIMIT 1",
        (),
    )
    if unread:
        return {"started": False,
                "reason": f"{unread['title']} is still unread — mark it read first"}

    phase = await db.fetchone(
        "SELECT slug, course, title, summary, url FROM hq.course_phases"
        " WHERE slug = %s AND course = %s AND status = 'pending'",
        (slug, course),
    )
    if not phase:
        raise HTTPException(404, f"no pending phase {slug!r} in {course!r}")

    payload = course_payload(dict(phase))
    task_id = await engine.dispatch(
        agent="hunter",
        title=f"Study: {str(phase['title'])[:64]}",
        brief=course_study_brief(payload),
        source="web",
        payload=payload,
        dedup_key=f"course-phase:{slug}",
    )
    return {"started": True, "task_id": task_id, "title": phase["title"]}


@router.post("/courses/{course}/activate", operation_id="activateCourse")
async def activate_course(course: str) -> dict:
    """Work this course next, and only this one."""
    row = await db.fetchone(
        "SELECT count(*) AS n FROM hq.course_phases WHERE course = %s", (course,)
    )
    if not row or not row["n"]:
        raise HTTPException(404, f"no course {course!r}")
    await db.execute(
        "INSERT INTO hq.control (key, value) VALUES (%s, to_jsonb(%s::text))"
        " ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value",
        (ACTIVE_COURSE_KEY, course),
    )
    return {"active": course}
