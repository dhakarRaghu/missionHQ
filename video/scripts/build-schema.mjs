#!/usr/bin/env node
// build-schema.mjs: writes spec/video-spec.schema.json and spec/narration.schema.json.
// The schema is written as code here so the limits sit in one readable table. Run after any contract change:
//   node scripts/build-schema.mjs
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const str = (max, extra = {}) => ({ type: "string", minLength: 1, maxLength: max, ...extra });
const obj = (properties, required) => ({ type: "object", additionalProperties: false, properties, required });
const arr = (items, min, max) => ({ type: "array", items, minItems: min, maxItems: max });

const tone = { $ref: "#/definitions/tone" };
const at = { $ref: "#/definitions/at" };
const panelBase = { caption: str(90), note: str(120) };

const panels = {
  chips: obj({ kind: { const: "chips" }, ...panelBase,
    items: arr(obj({ text: str(64), tone, at }, ["text", "at"]), 1, 6) }, ["kind", "items"]),
  flow: obj({ kind: { const: "flow" }, ...panelBase,
    nodes: arr(obj({ label: str(22), sub: str(36), tone, at }, ["label", "at"]), 2, 5) }, ["kind", "nodes"]),
  stats: obj({ kind: { const: "stats" }, ...panelBase,
    items: arr(obj({ value: str(14), label: str(40), tone, at }, ["value", "at"]), 1, 3) }, ["kind", "items"]),
  bars: obj({ kind: { const: "bars" }, ...panelBase,
    items: arr(obj({ label: str(28), value: { type: "number", exclusiveMinimum: 0 }, display: str(16), tone, at },
      ["label", "value", "display", "at"]), 2, 6) }, ["kind", "items"]),
  table: obj({ kind: { const: "table" }, ...panelBase,
    columns: arr(str(18), 2, 4),
    rows: arr(obj({ cells: arr(str(22), 2, 4), tone, at }, ["cells", "at"]), 1, 6) }, ["kind", "columns", "rows"]),
  equation: obj({ kind: { const: "equation" }, ...panelBase,
    lines: arr(obj({ text: str(48), tone, at }, ["text", "at"]), 1, 5) }, ["kind", "lines"]),
  compare: obj({ kind: { const: "compare" }, ...panelBase,
    left: { $ref: "#/definitions/compareSide" }, right: { $ref: "#/definitions/compareSide" }, at_left: at, at_right: at },
    ["kind", "left", "right", "at_left", "at_right"]),
  prompt: obj({ kind: { const: "prompt" }, ...panelBase, title: str(40),
    lines: arr(obj({ text: str(56), tone, at }, ["text", "at"]), 1, 8) }, ["kind", "lines"]),
};

const panelRef = { $ref: "#/definitions/panel" };
const visual = { panel: panelRef, panels: arr(panelRef, 2, 3) };
// A visual step has exactly one of `panel` and `panels`.
const oneVisual = { oneOf: [{ required: ["panel"] }, { required: ["panels"] }] };
const vstep = (name, extra = {}, req = []) => ({
  ...obj({ step: { const: name }, ...visual, ...extra }, ["step", ...req]), ...oneVisual,
});

const steps = {
  claim: obj({ step: { const: "claim" } }, ["step"]),
  situation: vstep("situation"),
  picture: vstep("picture"),
  think: obj({ step: { const: "think" }, first: str(70), misses: str(70), real: str(90) }, ["step", "first", "misses", "real"]),
  mechanism: obj({ step: { const: "mechanism" }, items: arr(obj({ text: str(48), at }, ["text", "at"]), 2, 6), side: panelRef },
    ["step", "items"]),
  number: vstep("number", { source: obj({ text: str(160) }, ["text"]) }),
  keypoints: obj({ step: { const: "keypoints" } }, ["step"]),
  bridge: vstep("bridge", { label: str(40) }),
  panel: vstep("panel"),
};

const schema = {
  $schema: "http://json-schema.org/draft-07/schema#",
  $id: "https://missionhq.local/video/video-spec.schema.json",
  title: "VideoSpec, version 1 (video/SPEC.md)",
  description: "Generated by video/scripts/build-schema.mjs. Same contract as video/src/spec/types.ts.",
  definitions: {
    tone: { enum: ["ink", "ok", "bad", "warn", "info", "accent"] },
    at: { type: "string", pattern: "^[a-z]{1,2}[0-9]+[a-z]?$", maxLength: 8 },
    compareSide: obj({ title: str(28), items: arr(str(40), 1, 4) }, ["title", "items"]),
    ...Object.fromEntries(Object.entries(panels).map(([k, v]) => [`panel_${k}`, v])),
    panel: {
      type: "object",
      required: ["kind"],
      properties: { kind: { enum: Object.keys(panels) } },
      discriminator: { propertyName: "kind" },
      oneOf: Object.keys(panels).map((k) => ({ $ref: `#/definitions/panel_${k}` })),
    },
    ...Object.fromEntries(Object.entries(steps).map(([k, v]) => [`step_${k}`, v])),
    step: {
      type: "object",
      required: ["step"],
      properties: { step: { enum: Object.keys(steps) } },
      discriminator: { propertyName: "step" },
      oneOf: Object.keys(steps).map((k) => ({ $ref: `#/definitions/step_${k}` })),
    },
    beat: {
      ...obj({
        id: { type: "string", pattern: "^(cold|title|c([1-9]|1[0-9]|20)|payoff|recap|end)$" },
        kind: { enum: ["cold", "title", "concept", "payoff", "recap", "end"] },
        heading: str(60),
        count: str(12),
        mark: str(40),
        steps: arr({ $ref: "#/definitions/step" }, 1, 9),
      }, ["id", "kind"]),
      allOf: [
        { if: { properties: { kind: { const: "concept" } } }, then: { required: ["heading", "count", "steps"] } },
        { if: { properties: { kind: { const: "payoff" } } }, then: { required: ["heading", "steps"] } },
        { if: { properties: { kind: { const: "cold" } } }, then: { required: ["steps"] } },
        { if: { properties: { kind: { enum: ["title", "recap", "end"] } } }, then: { not: { required: ["steps"] } } },
      ],
    },
  },
  ...obj({
    version: { const: 1 },
    id: str(80, { pattern: "^[a-z0-9][a-z0-9-]*$" }),
    mode: { enum: ["course", "youtube", "article"] },
    series: str(40),
    number: { type: ["integer", "null"], minimum: 1 },
    title: str(70),
    label: str(40),
    next: obj({ number: { type: ["integer", "null"], minimum: 1 }, title: { anyOf: [str(60), { type: "null" }] } }, ["number", "title"]),
    site: str(40),
    beats: arr({ $ref: "#/definitions/beat" }, 3, 26),
  }, ["version", "id", "mode", "series", "number", "title", "label", "beats"]),
};

const line = obj({
  key: { type: "string", pattern: "^[a-z]{1,2}[0-9]+[a-z]?$", maxLength: 8 },
  text: { type: "string", minLength: 1, maxLength: 400 },
  say: { type: "string", minLength: 1, maxLength: 600 },
  voice: { type: "string" },
}, ["key", "text"]);

const narration = {
  $schema: "http://json-schema.org/draft-07/schema#",
  $id: "https://missionhq.local/video/narration.schema.json",
  title: "Narration file (<id>.narration.json, video/SPEC.md)",
  description: "Generated by video/scripts/build-schema.mjs.",
  ...obj({
    engine: { enum: ["kokoro", "say"] },
    voice: { type: "string" },
    rate: { type: "number" },
    speed: { type: "number", minimum: 0.5, maximum: 1.5 },
    lang: { type: "string" },
    fadeTailS: { type: "number", minimum: 0 },
    leadinS: { type: "number", minimum: 0 },
    holdS: { type: "number", minimum: 0 },
    gapS: { type: "number", minimum: 0 },
    beats: {
      type: "object",
      propertyNames: { pattern: "^(cold|title|c([1-9]|1[0-9]|20)|payoff|recap|end)$" },
      additionalProperties: obj({
        chapter: str(60),
        cueLeadS: { type: "number", minimum: 0, maximum: 0.5 },
        preDelayS: { type: "number", minimum: 0 },
        leadinS: { type: "number", minimum: 0 },
        holdS: { type: "number", minimum: 0 },
        gapS: { type: "number", minimum: 0 },
        voice: { type: "string" },
        lines: arr(line, 1, 60),
      }, ["lines"]),
    },
  }, ["beats"]),
};

writeFileSync(join(root, "spec/video-spec.schema.json"), JSON.stringify(schema, null, 2) + "\n");
writeFileSync(join(root, "spec/narration.schema.json"), JSON.stringify(narration, null, 2) + "\n");
console.log("wrote spec/video-spec.schema.json and spec/narration.schema.json");
